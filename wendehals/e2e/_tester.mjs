import { chromium } from 'playwright-core';
const S = '/tmp/claude-0/-home-user-sqllerntool/878bf157-62e1-5277-9613-aa52fea7fb91/scratchpad';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 920 }, acceptDownloads: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', e => errs.push('pageerror ' + e.message));
page.on('console', m => { if (['error','warning'].includes(m.type())) errs.push(m.type()+' '+m.text()); });
await page.goto('file:///home/user/sqllerntool/wendehals/dist/index.html?editor');
await page.waitForFunction(() => window.__editor);
await page.waitForTimeout(500);
const ed = (fn, arg) => page.evaluate(`(${fn.toString()})(window.__editor, ${JSON.stringify(arg ?? null)})`);
const shot = n => page.screenshot({ path: `${S}/${n}.png` });
const w2b = async (x,y)=> { const r = await ed((e,[x,y])=>e.ansicht.weltZuBild(x,y),[x,y]); const b = await page.evaluate(()=>{const r=document.querySelector('#plan canvas').getBoundingClientRect();return [r.left,r.top]}); return [r[0]+b[0], r[1]+b[1]]; };
const info = () => ed(e => ({g:e.state.gebietId, w:e.state.werkzeug, au:e.state.auswahl, f:e.gebiet().formteile.length, o:e.gebiet().objekte.length, k:e.gebiet().knoten.length, ga:e.gebiet().gaenge.length, m:e.state.meldung, ung:e.ungespeichert()}));
const log = (...a)=>console.log(...a);
const click = async (x,y,o)=>{const [bx,by]=await w2b(x,y); await page.mouse.click(bx,by,o);};
const drag = async (x1,y1,x2,y2,steps=8)=>{const [a,b]=await w2b(x1,y1);const [c,d]=await w2b(x2,y2); await page.mouse.move(a,b); await page.mouse.down(); await page.mouse.move(c,d,{steps}); await page.mouse.up();};
globalThis.T = {page, ed, shot, w2b, info, log, click, drag, errs, S, browser, ctx};
await (await import(process.argv[2])).default(globalThis.T);
log('ERRS', errs);
await browser.close();
